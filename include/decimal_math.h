/* decimal_math.h - <math.h> transcendentals for _Decimal32/64/128 (C23,
 * tracker #828, phase 2 of #402). bid{32,64,128}_{sqrt,exp,log,pow,sin,
 * cos,...} via the Intel BID library, opt-in with CCCC_HAS_DECIMAL=1 (see
 * man/VM.md's Decimal Floating-Point section).
 *
 * This entire header is a compile error without CCCC_HAS_DECIMAL: unlike
 * <math.h>'s binary-float functions, there is no fallback here (real
 * decimal arithmetic is opt-in in the first place -- see decimal.c's
 * top-of-file comment for the "no lossy emulation" rationale, same as
 * #824's POSIX policy).
 *
 * Every function below is a thin static inline wrapper around one of six
 * op-dispatch entry points (src/stdlib/decimal_math.c's __cccc_dec_math1/
 * math2/math3/mathi/mathn/mathp), each taking raw addresses so no BID type
 * has to appear here. Op numbers below MUST stay in sync with that file's
 * enums -- there is no shared header between the compiler-internal .c and
 * this guest-facing one, so a mismatch here is a silent miscompile.
 */
