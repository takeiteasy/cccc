/* __cccc_dec_mathp's FREXP case writes the exponent through outp as a
 * plain `int` (not `long long`) -- `e` here is only sized `long long` so
 * its address is a valid outp for the shared long-long-typed entry point.
 * That means the write only ever touches e's low 4 bytes, and `(int)e`
 * below only ever reads them back -- correct on the little-endian targets
 * this project builds for (aarch64/x86_64, per man/COVERAGE.md), not
 * portable to a big-endian host without widening the write. */
#define __CCCC_DECM_FREXP(FN, TY, W) \
    static inline TY FN(TY x, int *exp) { \
        TY xx = x, r; \
        long long e = 0; \
        __cccc_dec_mathp(__CCCC_DECMP_FREXP, W, (long long)&r, (long long)&xx, (long long)&e); \
        *exp = (int)e; \
        return r; \
    }

#define __CCCC_DECM_MODF(FN, TY, W) \
    static inline TY FN(TY x, TY *iptr) { \
        TY xx = x, r, ip; \
        __cccc_dec_mathp(__CCCC_DECMP_MODF, W, (long long)&r, (long long)&xx, (long long)&ip); \
        *iptr = ip; \
        return r; \
    }

/* nexttoward's second argument is always _Decimal128, regardless of the
 * first argument's width -- matches C's nexttoward(x, long double) shape,
 * with _Decimal128 standing in for "widest". */
#define __CCCC_DECM_NEXTTOWARD(FN, TY, W) \
    static inline TY FN(TY x, _Decimal128 y) { \
        TY xx = x, r; \
        _Decimal128 yy = y; \
        __cccc_dec_math2(__CCCC_DECM2_NEXTTOWARD, W, (long long)&r, (long long)&xx, (long long)&yy); \
        return r; \
    }

