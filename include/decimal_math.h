/* -- per-width typed wrappers, generated by X-macro over 32/64/128 ------- */

#define __CCCC_DECM_UNARY(FN, OP, TY, W) \
    static inline TY FN(TY x) { \
        TY xx = x, r; \
        __cccc_dec_math1(OP, W, (long long)&r, (long long)&xx); \
        return r; \
    }

#define __CCCC_DECM_BINARY(FN, OP, TY, W) \
    static inline TY FN(TY x, TY y) { \
        TY xx = x, yy = y, r; \
        __cccc_dec_math2(OP, W, (long long)&r, (long long)&xx, (long long)&yy); \
        return r; \
    }

#define __CCCC_DECM_TERNARY(FN, OP, TY, W) \
    static inline TY FN(TY x, TY y, TY z) { \
        TY xx = x, yy = y, zz = z, r; \
        __cccc_dec_math3(OP, W, (long long)&r, (long long)&xx, (long long)&yy, (long long)&zz); \
        return r; \
    }

#define __CCCC_DECM_PRED(FN, OP, TY, W) \
    static inline int FN(TY x) { \
        TY xx = x; \
        return (int)__cccc_dec_mathi(OP, W, (long long)&xx, 0); \
    }

